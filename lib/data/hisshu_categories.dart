/// 大項目（原文そのまま）の一覧
List<String> hisshuMajors() => _hisshu.keys.toList();

/// 指定大項目の中項目（原文そのまま）の一覧
List<String> hisshuMids(String major) => _hisshu[major]?.keys.toList() ?? const [];

/// 指定（大項目, 中項目）の小項目一覧。
/// mid を省略/ null にすると大項目配下の全小項目を結合して返す。
List<String> hisshuTopicsOf(String major, [String? mid]) {
  final map = _hisshu[major];
  if (map == null) return const [];
  if (mid == null) {
    return map.values.fold<List<String>>(<String>[], (acc, v) => acc..addAll(v));
  }
  return map[mid] ?? const [];
}

/// 中項目ランダム選択（ユーザー未選択時の裏選択用）
String pickRandomHisshuMid(String major, {int? seed}) {
  final mids = hisshuMids(major);
  if (mids.isEmpty) return '';
  final rnd = seed == null ? Random() : Random(seed);
  return mids[rnd.nextInt(mids.length)];
}

/// 小項目ランダム選択（必要に応じて使用）
String pickRandomHisshuTopic(String major, {String? mid, int? seed}) {
  final topics = hisshuTopicsOf(major, mid);
  if (topics.isEmpty) return '';
  final rnd = seed == null ? Random() : Random(seed);
  return topics[rnd.nextInt(topics.length)];
}

