/// 大項目一覧
List<String> psychiatricNursingMajors() => _psychiatric.keys.toList();

/// 指定大項目の中項目一覧
List<String> psychiatricNursingMids(String major) =>
    _psychiatric[major]?.keys.toList() ?? const [];

/// 指定（大項目, 中項目）の小項目（キーワード）
/// mid を null にすると、その大項目配下の全キーワードを連結して返す
List<String> psychiatricNursingTopicsOf(String major, [String? mid]) {
  final map = _psychiatric[major];
  if (map == null) return const [];
  if (mid == null) {
    final all = <String>[];
    for (final v in map.values) {
      all.addAll(v);
    }
    return all;
  }
  return map[mid] ?? const [];
}