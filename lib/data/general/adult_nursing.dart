List<String> adultNursingMajors() => _adult.keys.toList();

// 指定大項目の中項目一覧
List<String> adultNursingMids(String major) =>
    _adult[major]?.keys.toList() ?? const [];

// 指定（大項目, 中項目）の小項目（mid 省略/空なら全小項目を連結）
List<String> adultNursingTopicsOf(String major, [String? mid]) {
  final map = _adult[major];
  if (map == null) return const [];
  if (mid == null || mid.isEmpty) {
    final out = <String>[];
    for (final xs in map.values) {
      out.addAll(xs);
    }
    return out;
  }
  return map[mid] ?? const [];
}