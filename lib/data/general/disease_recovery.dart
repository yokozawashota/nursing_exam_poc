/// 大項目一覧
List<String> diseaseRecoveryMajors() => List.unmodifiable(_diseaseRecovery.keys);

/// 指定大項目の中項目一覧
List<String> diseaseRecoveryMids(String major) =>
    List.unmodifiable(_diseaseRecovery[major]?.keys ?? const <String>[]);

/// 指定（大項目, 中項目）の小項目（キーワード）
/// [mid] が null/空文字の場合は、その大項目配下すべての小項目をフラットに返す。
List<String> diseaseRecoveryTopicsOf(String major, String? mid) {
  final box = _diseaseRecovery[major];
  if (box == null) return const [];
  if (mid == null || mid.isEmpty) {
    return List.unmodifiable(box.values.expand((e) => e).toList());
  }
  return List.unmodifiable(box[mid] ?? const []);
}