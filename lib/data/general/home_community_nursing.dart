/// 大項目一覧（categories.dart から参照）
List<String> homeCommunityNursingMajors() => _homeCommunity.keys.toList();

/// 指定大項目の中項目一覧
List<String> homeCommunityNursingMids(String major) =>
    _homeCommunity[major]?.keys.toList() ?? const [];

/// 指定（大項目, 中項目）の小項目（キーワード）
/// mid を null にすると、その大項目配下の全キーワードを結合して返す
List<String> homeCommunityNursingTopicsOf(String major, [String? mid]) {
  final map = _homeCommunity[major];
  if (map == null) return const [];
  if (mid == null) {
    return map.values.fold<List<String>>(
      <String>[],
          (acc, v) => acc..addAll(v),
    );
  }
  return map[mid] ?? const [];
}