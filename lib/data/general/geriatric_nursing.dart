/// 大項目一覧
List<String> geriatricNursingMajors() => _geri.keys.toList();

/// 指定大項目の中項目一覧
List<String> geriatricNursingMids(String major) =>
    _geri[major]?.keys.toList() ?? const [];

/// 指定（大項目, 中項目）の小項目（midがnullなら大項目配下すべて）
List<String> geriatricNursingTopicsOf(String major, [String? mid]) {
  final map = _geri[major];
  if (map == null) return const [];
  if (mid == null) {
    return map.values.fold<List<String>>(<String>[], (acc, v) => acc..addAll(v));
  }
  return map[mid] ?? const [];
}