/// 大項目一覧（順序保持）
List<String> healthSocialMajors() => _healthSocial.keys.toList();

/// 指定大項目の中項目一覧
List<String> healthSocialMids(String major) =>
    _healthSocial[major]?.keys.toList() ?? const [];

/// 指定（大項目, 中項目）に対応する小項目一覧。
/// [mid] が null または空なら、その大項目配下の全小項目を結合して返す。
List<String> healthSocialTopicsOf(String major, String? mid) {
  final mids = _healthSocial[major];
  if (mids == null) return const [];
  if (mid == null || mid.isEmpty) {
    return mids.values.expand((e) => e).toList();
  }
  return mids[mid] ?? const [];
}