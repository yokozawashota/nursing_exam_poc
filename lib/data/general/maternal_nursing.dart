/// 大項目一覧
List<String> maternalNursingMajors() => _maternal.keys.toList();

/// 指定大項目の中項目一覧
List<String> maternalNursingMids(String major) =>
    _maternal[major]?.keys.toList() ?? const [];

/// 指定（大項目, 中項目）の小項目（キーワード）
/// mid を null にすると、その大項目配下の全キーワードを連結して返す
List<String> maternalNursingTopicsOf(String major, [String? mid]) {
  final map = _maternal[major];
  if (map == null) return const [];
  if (mid == null) {
    return map.values.fold<List<String>>(<String>[], (acc, v) => acc..addAll(v));
  }
  return map[mid] ?? const [];
}