/// 大項目一覧
List<String> pediatricNursingMajors() => _pediatric.keys.toList();

/// 指定大項目の中項目一覧
List<String> pediatricNursingMids(String major) =>
    _pediatric[major]?.keys.toList() ?? const [];

/// 指定（大項目, 中項目）の小項目（キーワード）
/// mid を null にすると、その大項目配下の全キーワードを結合して返す
List<String> pediatricNursingTopicsOf(String major, [String? mid]) {
  final map = _pediatric[major];
  if (map == null) return const [];
  if (mid == null) {
    final all = <String>[];
    for (final m in map.keys) {
      all.addAll(map[m] ?? const []);
    }
    return all;
  }
  return map[mid] ?? const [];
}